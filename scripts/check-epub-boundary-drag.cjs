const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require(process.env.HARMONY_TYPESCRIPT);
const root = path.join(__dirname, '../read-books/entry/src/main/ets');
const source = fs.readFileSync(path.join(root, 'reader/EpubBoundaryDrag.ets'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const motionCode = ts.transpileModule(fs.readFileSync(path.join(root, 'reader/PageTurnMotion.ets'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const motion = {}; new Function('exports', motionCode)(motion);
const out = {}; new Function('exports', 'require', code)(out, () => motion);
const drag = new out.EpubBoundaryDrag();
drag.start(900, 300, 4, 5, false, 1200);
assert(drag.move(300, 301));
assert.equal(drag.offset, -600); assert.equal(drag.delta, 1); assert.equal(drag.side, 1);
assert.equal(1200 + drag.offset, 600, 'halfway through the swipe the next prelaid chapter starts at mid-screen, before release');
assert(drag.commit());
drag.move(880, 300); assert(!drag.commit(), 'reversing a half swipe cancels without turning');
drag.move(950, 300); assert.equal(drag.offset, 0, 'do not expose the opposite empty edge');
drag.start(200, 300, 0, 5, false, 1200); drag.move(800, 300);
assert.equal(drag.delta, -1); assert.equal(drag.side, -1); assert.equal(drag.offset, 600);
drag.start(900, 300, 2, 5, false, 1200); assert(!drag.move(300, 300), 'intra-chapter gesture stays entirely inside ArkWeb');
drag.start(200, 300, 4, 5, true, 1200); drag.move(800, 300); assert.equal(drag.delta, 1, 'RTL next chapter is on the left');
drag.start(900, 300, 0, 1, false, 1200); assert(!drag.move(880, 500), 'vertical gestures do not grab the native pager');
drag.reset(); assert(!drag.move(0, 0));
const followup = new out.EpubFollowupInput();
followup.start(900, 300, false, 1200);
assert.equal(followup.finish(300, 300), 1, 'a turn begun during settling survives the surface handoff');
assert.equal(followup.finish(300, 300), 0, 'the same Up cannot turn twice');
followup.start(300, 300, false, 1200); assert.equal(followup.finish(900, 300), -1);
followup.start(900, 300, false, 1200); assert.equal(followup.finish(880, 300), 0, 'short cancel is not a tap');
followup.start(900, 300, false, 1200); assert.equal(followup.finish(880, 600), 0, 'vertical movement is not a turn');
followup.start(300, 300, true, 1200); assert.equal(followup.finish(900, 300), 1, 'RTL followup direction');
followup.start(1100, 300, false, 1200); assert.equal(followup.finish(1100, 300), 1, 'edge tap during native settle');
followup.start(300, 300, false, 1200); followup.reset(); assert.equal(followup.finish(900, 300), 0, 'cancel/lifecycle clears pending contact');
const reader = fs.readFileSync(path.join(root, 'pages/EpubReader.ets'), 'utf8');
assert.match(reader, /point\.windowX/, 'moving Web local coordinates cannot be used for finger motion');
assert.match(reader, /slot\.page === edge/, 'preview must already be at the first/last screen before the finger starts');
assert.match(reader, /onTouch\(\(event: TouchEvent\) => this\.settleFollowup\(event\)\)/, 'root retains touches on the incoming surface before it becomes the active Web');
assert.match(reader, /this\.navigate\(locator\.path, '', locator, this\.queuedTurns\)/, 'followup released before settle completion must survive navigation queue initialization');
assert.match(reader, /if \(!keepFollowup\) \{ this\.followupInput\.reset\(\); this\.queuedTurns = 0;/, 'leaving/panel/reflow cancels stale followup intents');
const settings = fs.readFileSync(path.join(root, 'components/ReadingSettingsPanel.ets'), 'utf8');
assert.match(settings, /id\('reading_settings_panel'\).*backgroundColor\(this\.palette\.chrome\)/);
assert(!settings.includes("backgroundColor($r('app.color.background'))"));
console.log('EPUB boundary drag passed: halfway reveal, forward/reverse, cancel, RTL, intra-chapter isolation and warm panel palette.');
